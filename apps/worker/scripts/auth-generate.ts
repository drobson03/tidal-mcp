/**
 * Generates the next migration file for Better Auth's tables. It never
 * touches D1: alchemy applies `migrations/` on deploy (see `src/Database.ts`).
 *
 * Better Auth's schema comes from its plugins, and its migrator diffs that
 * against a live database. So this replays the existing migrations into an
 * in-memory SQLite database and writes only what's missing as the next
 * numbered file. Re-run after changing plugins or user fields.
 *
 *   pnpm --filter @tidal-mcp/worker auth:generate
 */
import { getMigrations } from "better-auth/db/migration"
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { DatabaseSync } from "node:sqlite"
import * as Allowlist from "../src/auth/Allowlist.ts"
import { authOptions } from "../src/auth/BetterAuth.ts"

const dir = new URL("../migrations/", import.meta.url)
mkdirSync(dir, { recursive: true })
const existing = readdirSync(dir).filter((file) => file.endsWith(".sql")).sort()

const database = new DatabaseSync(":memory:")
for (const file of existing) database.exec(readFileSync(new URL(file, dir), "utf8"))

const unused = () => Promise.reject(new Error("not used when generating migrations"))
const options = authOptions({
  origin: "http://localhost",
  mcpPath: "/mcp",
  database,
  secret: "migration-generation-secret-not-used-at-runtime",
  allowlist: Allowlist.parse(""),
  fetchClientMetadata: unused,
  tidal: {
    clientId: "unused",
    clientSecret: "unused",
    loginUrl: "https://login.tidal.com/authorize",
    tokenUrl: "https://auth.tidal.com/v1/oauth2/token",
    scopes: [],
    exchangeCode: unused,
    fetchProfile: unused
  }
})
// SQLite stores `string[]` columns as JSON text; the migrator warns about it.
const { compileMigrations, toBeAdded, toBeCreated } = await getMigrations({ ...options, logger: { level: "error" } })

if (toBeAdded.length === 0 && toBeCreated.length === 0) {
  console.log("Schema is up to date.")
} else {
  const sql = await compileMigrations()
  const number = String(existing.length + 1).padStart(4, "0")
  const name = `${number}_better_auth.sql`
  writeFileSync(new URL(name, dir), `-- Generated by scripts/auth-generate.ts\n${sql.trim()}\n`)
  console.log(`Wrote migrations/${name}. Alchemy applies it on the next deploy.`)
}
